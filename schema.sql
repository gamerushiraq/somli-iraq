create extension if not exists pgcrypto;

create type public.profile_role as enum ('buyer', 'seller', 'admin');
create type public.product_condition as enum ('new', 'used', 'refurbished');
create type public.product_status as enum ('draft', 'active', 'paused', 'removed');
create type public.request_status as enum ('open', 'closed', 'cancelled');
create type public.offer_status as enum ('sent', 'accepted', 'rejected', 'withdrawn');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null check (char_length(display_name) between 1 and 100),
  phone text,
  role public.profile_role not null default 'buyer',
  governorate text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.categories (
  id bigint generated by default as identity primary key,
  name_ar text not null unique,
  slug text not null unique,
  parent_id bigint references public.categories(id) on delete set null,
  is_active boolean not null default true
);

create table public.products (
  id uuid primary key default gen_random_uuid(),
  seller_id uuid not null references public.profiles(id) on delete restrict,
  category_id bigint not null references public.categories(id),
  title text not null check (char_length(title) between 2 and 140),
  description text check (char_length(description) <= 3000),
  price numeric(14,2) check (price is null or price >= 0),
  currency text not null default 'IQD' check (currency = 'IQD'),
  condition public.product_condition not null default 'new',
  governorate text not null,
  status public.product_status not null default 'draft',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.product_images (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products(id) on delete cascade,
  storage_path text not null,
  alt_text text,
  sort_order int not null default 0,
  created_at timestamptz not null default now(),
  unique(product_id, storage_path)
);

create table public.quote_requests (
  id uuid primary key default gen_random_uuid(),
  buyer_id uuid not null references public.profiles(id) on delete restrict,
  category_id bigint references public.categories(id),
  title text not null check (char_length(title) between 2 and 140),
  details text check (char_length(details) <= 3000),
  budget numeric(14,2) check (budget is null or budget >= 0),
  governorate text not null,
  condition_preference text not null default 'any'
    check (condition_preference in ('new','used','any')),
  status public.request_status not null default 'open',
  expires_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- A buyer can optionally direct a quote request to specific products.
create table public.request_targets (
  request_id uuid not null references public.quote_requests(id) on delete cascade,
  product_id uuid not null references public.products(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(request_id, product_id)
);

create table public.offers (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null references public.quote_requests(id) on delete cascade,
  seller_id uuid not null references public.profiles(id) on delete restrict,
  product_id uuid references public.products(id) on delete set null,
  price numeric(14,2) not null check (price >= 0),
  delivery_fee numeric(14,2) not null default 0 check (delivery_fee >= 0),
  warranty text check (char_length(warranty) <= 500),
  notes text check (char_length(notes) <= 1500),
  valid_until timestamptz,
  status public.offer_status not null default 'sent',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(request_id, seller_id)
);

create table public.favorites (
  user_id uuid not null references public.profiles(id) on delete cascade,
  product_id uuid not null references public.products(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(user_id, product_id)
);

create table public.reviews (
  id uuid primary key default gen_random_uuid(),
  reviewer_id uuid not null references public.profiles(id) on delete restrict,
  seller_id uuid not null references public.profiles(id) on delete restrict,
  rating int not null check (rating between 1 and 5),
  comment text check (char_length(comment) <= 1500),
  created_at timestamptz not null default now(),
  check (reviewer_id <> seller_id),
  unique(reviewer_id, seller_id)
);

create table public.reports (
  id uuid primary key default gen_random_uuid(),
  reporter_id uuid not null references public.profiles(id) on delete restrict,
  product_id uuid references public.products(id) on delete cascade,
  seller_id uuid references public.profiles(id) on delete cascade,
  reason text not null check (char_length(reason) between 5 and 1000),
  status text not null default 'open' check (status in ('open','reviewing','resolved','dismissed')),
  created_at timestamptz not null default now()
);

create index products_category_status_idx on public.products(category_id, status);
create index products_governorate_idx on public.products(governorate);
create index products_price_idx on public.products(price) where status = 'active';
create index quote_requests_buyer_created_idx on public.quote_requests(buyer_id, created_at desc);
create index quote_requests_open_idx on public.quote_requests(governorate, category_id, created_at desc) where status = 'open';
create index offers_request_created_idx on public.offers(request_id, created_at);
create index offers_seller_created_idx on public.offers(seller_id, created_at desc);

