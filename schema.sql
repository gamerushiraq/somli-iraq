create policy "users read own profile"
  on public.profiles for select to authenticated using (auth.uid() = id);
create policy "users insert own profile"
  on public.profiles for insert to authenticated with check (auth.uid() = id);
create policy "users update own profile"
  on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

create policy "active categories readable by everyone"
  on public.categories for select to anon, authenticated using (is_active = true);

create policy "active products are public"
  on public.products for select to anon, authenticated using (status = 'active' or seller_id = auth.uid());
create policy "seller inserts own products"
  on public.products for insert to authenticated with check (seller_id = auth.uid());
create policy "seller updates own products"
  on public.products for update to authenticated using (seller_id = auth.uid()) with check (seller_id = auth.uid());
create policy "seller deletes own products"
  on public.products for delete to authenticated using (seller_id = auth.uid());

create policy "product images follow product visibility"
  on public.product_images for select to anon, authenticated using (
    exists(select 1 from public.products p where p.id = product_id and (p.status = 'active' or p.seller_id = auth.uid()))
  );
create policy "seller manages images of own products"
  on public.product_images for all to authenticated using (
    exists(select 1 from public.products p where p.id = product_id and p.seller_id = auth.uid())
  ) with check (
    exists(select 1 from public.products p where p.id = product_id and p.seller_id = auth.uid())
  );

create policy "buyer sees own quote requests"
  on public.quote_requests for select to authenticated using (buyer_id = auth.uid());
create policy "buyer creates own quote requests"
  on public.quote_requests for insert to authenticated with check (buyer_id = auth.uid());
create policy "buyer updates own quote requests"
  on public.quote_requests for update to authenticated using (buyer_id = auth.uid()) with check (buyer_id = auth.uid());

create policy "buyer manages own request targets"
  on public.request_targets for all to authenticated using (
    exists(select 1 from public.quote_requests r where r.id = request_id and r.buyer_id = auth.uid())
  ) with check (
    exists(select 1 from public.quote_requests r where r.id = request_id and r.buyer_id = auth.uid())
  );

create policy "buyer and targeted seller can read offers"
  on public.offers for select to authenticated using (
    seller_id = auth.uid() or exists(select 1 from public.quote_requests r where r.id = request_id and r.buyer_id = auth.uid())
  );
create policy "seller sends own offer"
  on public.offers for insert to authenticated with check (
    seller_id = auth.uid() and exists(
      select 1 from public.quote_requests r
      where r.id = request_id and r.status = 'open'
    )
  );
create policy "seller updates own offer"
  on public.offers for update to authenticated using (seller_id = auth.uid()) with check (seller_id = auth.uid());

create policy "users manage own favorites"
  on public.favorites for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

create policy "reviews readable by everyone"
  on public.reviews for select to anon, authenticated using (true);
create policy "users create own reviews"
  on public.reviews for insert to authenticated with check (reviewer_id = auth.uid());

create policy "users read own reports"
  on public.reports for select to authenticated using (reporter_id = auth.uid());
create policy "users create own reports"
  on public.reports for insert to authenticated with check (reporter_id = auth.uid());

